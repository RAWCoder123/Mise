export const catalogs: Readonly<Record<AppLocale, Catalog>> = {
  en,
  es,
  "zh-Hans": zhHans
};

export const LANGUAGE_OPTIONS: ReadonlyArray<{
  locale: AppLocale;
  nativeName: string;
  translatedNameKey: MessageKey;
}> = [
  { locale: "en", nativeName: "English", translatedNameKey: "settings.language.english" },
  { locale: "es", nativeName: "Español", translatedNameKey: "settings.language.spanish" },
  { locale: "zh-Hans", nativeName: "简体中文", translatedNameKey: "settings.language.chineseSimplified" }
];

export function isAppLocale(value: unknown): value is AppLocale {
  return typeof value === "string" && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function resolveSupportedLocale(value: string | null | undefined): AppLocale {
  return matchSupportedLocale(value) ?? DEFAULT_LOCALE;
}

export function detectDeviceLocale(): AppLocale {
  const browser = (globalThis as typeof globalThis & {
    navigator?: { language?: string; languages?: readonly string[] };
  }).navigator;
  const candidates = [...(browser?.languages ?? []), browser?.language];

  try {
    candidates.push(Intl.DateTimeFormat().resolvedOptions().locale);
  } catch {
    // Some older runtimes do not expose a resolved locale. English remains the safe fallback.
  }

  for (const candidate of candidates) {
    const locale = matchSupportedLocale(candidate);
    if (locale) return locale;
  }

  return DEFAULT_LOCALE;
}

export function translate(locale: AppLocale, key: MessageKey, values: MessageValues = {}): string {
  const template = catalogs[locale][key] ?? catalogs[DEFAULT_LOCALE][key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

export function matchSupportedLocale(value: string | null | undefined): AppLocale | null {
  if (!value) return null;
  const normalized = value.trim().replace(/_/g, "-").toLowerCase();
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (normalized === "es" || normalized.startsWith("es-")) return "es";
  if (
    normalized === "zh" ||
    normalized === "zh-hans" ||
    normalized.startsWith("zh-hans-") ||
    normalized === "zh-cn" ||
    normalized.startsWith("zh-cn-") ||
    normalized === "zh-sg" ||
    normalized.startsWith("zh-sg-")
  ) {
    return "zh-Hans";
  }
  return null;
}
