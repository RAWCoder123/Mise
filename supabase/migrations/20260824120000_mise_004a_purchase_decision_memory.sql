create function public.exclude_purchase_decision_event(
  p_restaurant_id uuid,
  p_event_id uuid
)
returns public.purchase_decision_events
language plpgsql
security definer
set search_path = ''
as $$
declare
  target public.purchase_decision_events%rowtype;
  existing public.purchase_decision_events%rowtype;
  audit_id uuid;
  audit_time timestamptz;
begin
  if auth.uid() is null or not private.has_restaurant_role(
    p_restaurant_id, array['owner', 'admin', 'manager']
  ) then
    raise exception 'Manager access required' using errcode = '42501';
  end if;
  select * into target from public.purchase_decision_events event
  where event.restaurant_id = p_restaurant_id and event.id = p_event_id
  for update;
  if not found or target.decision_type not in ('approve', 'approve_with_override', 'dismiss') then
    raise exception 'Purchase decision event not found' using errcode = 'P0002';
  end if;
  select * into existing from public.purchase_decision_events event
  where event.restaurant_id = p_restaurant_id
    and event.target_event_id = target.id
    and event.decision_type = 'exclude_from_learning';
  if found then return existing; end if;

  audit_id := gen_random_uuid();
  audit_time := pg_catalog.clock_timestamp();
  insert into public.audit_logs (
    id, restaurant_id, actor_user_id, action, entity_table, entity_id, metadata, created_at
  ) values (
    audit_id, p_restaurant_id, auth.uid(), 'purchase_decision_excluded_from_learning',
