create or replace function private.reject_purchase_decision_event_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE'
    and pg_catalog.current_setting('mise.inventory_event_tenant_delete', true) = 'true'
  then
    return old;
  end if;

  if tg_op = 'UPDATE'
    and old.actor_user_id is not null
    and new.actor_user_id is null
    and not exists (
      select 1 from auth.users auth_user where auth_user.id = old.actor_user_id
    )
    and (pg_catalog.to_jsonb(new) - 'actor_user_id')
      is not distinct from (pg_catalog.to_jsonb(old) - 'actor_user_id')
  then
    return new;
  end if;

  raise exception 'Purchase decision events are append-only' using errcode = '55000';
end;
$$;

