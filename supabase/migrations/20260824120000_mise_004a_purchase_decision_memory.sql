$$;

create or replace function private.record_purchase_decision_base_event(
  p_recommendation public.purchase_recommendations,
  p_decision text,
  p_recommended_quantity numeric,
  p_chosen_quantity numeric,
  p_authority jsonb,
  p_source_audit_log_id uuid,
  p_occurred_at timestamptz
)
returns public.purchase_decision_events
language plpgsql
security definer
set search_path = ''
as $$
declare
  item public.inventory_items%rowtype;
  actor_role text;
  decision_type text;
  event_row public.purchase_decision_events%rowtype;
  factor numeric;
begin
  if p_recommendation.generation_source not in ('mise_rules', 'legacy_client') then
    raise exception 'Only Mise-generated recommendations produce purchase memory evidence'
      using errcode = '22023';
  end if;
  actor_role := private.purchase_decision_actor_role(p_recommendation.restaurant_id);
  if actor_role is null or auth.uid() is null then
    raise exception 'Manager access required' using errcode = '42501';
  end if;
  select * into item from public.inventory_items candidate
  where candidate.restaurant_id = p_recommendation.restaurant_id
    and candidate.id = p_recommendation.inventory_item_id
    and candidate.supplier_id = p_recommendation.supplier_id
  for share;
  if not found
    or item.canonical_unit_verification_status <> 'verified'
    or item.canonical_unit is null
    or item.canonical_quantity_per_unit is null
  then
    raise exception 'Verified canonical purchase evidence is required'
      using errcode = '55000';
  end if;
  if p_source_audit_log_id is null then
    raise exception 'Purchase decision audit identity is required' using errcode = '55000';
  end if;
  factor := item.canonical_quantity_per_unit;
  decision_type := case
    when p_decision = 'dismiss' then 'dismiss'
    when p_chosen_quantity is distinct from p_recommended_quantity
      then 'approve_with_override'
    else 'approve'
  end;
  if p_decision not in ('approve', 'dismiss') then
    raise exception 'Unsupported purchase decision type' using errcode = '22023';
  end if;

  insert into public.purchase_decision_events (
    restaurant_id, actor_user_id, actor_role, decision_type,
    purchase_recommendation_id, inventory_item_id, supplier_id,
    recommendation_source, recommendation_unit,
    recommended_quantity, chosen_quantity, canonical_unit,
    canonical_quantity_per_unit, recommended_canonical_quantity,
    chosen_canonical_quantity, quantity_delta, quantity_ratio,
    planning_revision, context_evidence, source_audit_log_id,
    source_event_key, occurred_at
  ) values (
    p_recommendation.restaurant_id, auth.uid(), actor_role, decision_type,
    p_recommendation.id, p_recommendation.inventory_item_id,
    p_recommendation.supplier_id, p_recommendation.generation_source,
    p_recommendation.unit, p_recommended_quantity,
    case when p_decision = 'dismiss' then null else p_chosen_quantity end,
    item.canonical_unit, factor, p_recommended_quantity * factor,
    case when p_decision = 'dismiss' then null else p_chosen_quantity * factor end,
    case when p_decision = 'dismiss' then null
      else p_chosen_quantity - p_recommended_quantity end,
    case when p_decision = 'dismiss' then null
      else p_chosen_quantity / p_recommended_quantity end,
    p_recommendation.planning_revision,
    private.purchase_decision_context(p_authority, p_recommendation.planning_revision),
    p_source_audit_log_id, 'audit_log:' || p_source_audit_log_id::text,
    p_occurred_at
  ) returning * into event_row;
  return event_row;
end;
$$;

