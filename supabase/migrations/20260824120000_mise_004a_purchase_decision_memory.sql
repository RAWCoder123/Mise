    pg_catalog.jsonb_build_object(
      'target_event_id', target.id,
      'purchase_recommendation_id', target.purchase_recommendation_id
    ), audit_time
  );
  return private.record_purchase_decision_compensation(
    target, 'exclude_from_learning', audit_id,
    'purchase_decision_exclusion:' || target.id::text, audit_time
  );
end;
$$;

