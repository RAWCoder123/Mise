create function public.approve_purchase_recommendation(
  p_restaurant_id uuid,
  p_recommendation_id uuid,
  p_recommended_quantity numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  recommendation_prelock public.purchase_recommendations%rowtype;
  recommendation_snapshot public.purchase_recommendations%rowtype;
  result jsonb;
  audit_row public.audit_logs%rowtype;
  decision_event public.purchase_decision_events%rowtype;
  chosen_quantity numeric;
begin
  select * into recommendation_prelock
  from public.purchase_recommendations recommendation
  where recommendation.restaurant_id = p_restaurant_id
    and recommendation.id = p_recommendation_id;
  if not found then raise exception 'Recommendation not found' using errcode = 'P0002'; end if;
  perform private.lock_supplier_authority(
    p_restaurant_id, recommendation_prelock.supplier_id
  );
  select * into recommendation_snapshot
  from public.purchase_recommendations recommendation
  where recommendation.restaurant_id = p_restaurant_id
    and recommendation.id = p_recommendation_id
  for update;
  if recommendation_snapshot.supplier_id is distinct from recommendation_prelock.supplier_id then
    raise exception 'Recommendation supplier identity changed concurrently; retry'
      using errcode = '40001';
  end if;

  result := private.approve_purchase_recommendation_mise_003c_base(
    p_restaurant_id, p_recommendation_id, p_recommended_quantity
  );
  if result->>'outcome' = 'applied'
    and recommendation_snapshot.generation_source in ('mise_rules', 'legacy_client')
  then
    select * into audit_row from public.audit_logs audit
    where audit.restaurant_id = p_restaurant_id
      and audit.entity_id = p_recommendation_id
      and audit.action = 'recommendation_approved'
      and audit.actor_user_id = auth.uid()
    order by audit.created_at desc, audit.id desc limit 1;
    chosen_quantity := (result#>>'{recommendation,recommended_quantity}')::numeric;
    decision_event := private.record_purchase_decision_base_event(
      recommendation_snapshot, 'approve', recommendation_snapshot.recommended_quantity,
      chosen_quantity, result->'authority', audit_row.id, audit_row.created_at
    );
  elsif result->>'outcome' = 'already_applied'
    and recommendation_snapshot.generation_source in ('mise_rules', 'legacy_client')
  then
    select event.* into decision_event from public.purchase_decision_events event
    where event.restaurant_id = p_restaurant_id
      and event.purchase_recommendation_id = p_recommendation_id
      and event.decision_type in ('approve', 'approve_with_override')
    order by event.sequence desc limit 1;
  end if;
  if decision_event.id is not null then
    result := result || pg_catalog.jsonb_build_object(
      'purchaseDecisionEventId', decision_event.id
    );
  end if;
  return result;
end;
$$;

create function public.dismiss_purchase_recommendation(
  p_restaurant_id uuid,
  p_recommendation_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  recommendation_snapshot public.purchase_recommendations%rowtype;
  result jsonb;
  audit_row public.audit_logs%rowtype;
  decision_event public.purchase_decision_events%rowtype;
begin
  select * into recommendation_snapshot
  from public.purchase_recommendations recommendation
  where recommendation.restaurant_id = p_restaurant_id
    and recommendation.id = p_recommendation_id
  for update;
  if not found then raise exception 'Recommendation not found' using errcode = 'P0002'; end if;
  result := private.dismiss_purchase_recommendation_pre_mise_004a(
    p_restaurant_id, p_recommendation_id
  );
  if result->>'outcome' = 'applied'
    and recommendation_snapshot.generation_source in ('mise_rules', 'legacy_client')
  then
    select * into audit_row from public.audit_logs audit
    where audit.restaurant_id = p_restaurant_id
      and audit.entity_id = p_recommendation_id
      and audit.action = 'recommendation_dismissed'
      and audit.actor_user_id = auth.uid()
    order by audit.created_at desc, audit.id desc limit 1;
    decision_event := private.record_purchase_decision_base_event(
      recommendation_snapshot, 'dismiss', recommendation_snapshot.recommended_quantity,
      null, null, audit_row.id, audit_row.created_at
    );
  elsif result->>'outcome' = 'already_applied'
    and recommendation_snapshot.generation_source in ('mise_rules', 'legacy_client')
  then
    select event.* into decision_event from public.purchase_decision_events event
    where event.restaurant_id = p_restaurant_id
      and event.purchase_recommendation_id = p_recommendation_id
      and event.decision_type = 'dismiss'
    order by event.sequence desc limit 1;
  end if;
  if decision_event.id is not null then
    result := result || pg_catalog.jsonb_build_object(
      'purchaseDecisionEventId', decision_event.id
    );
  end if;
  return result;
end;
$$;

create function public.undo_purchase_recommendation_action(
  p_restaurant_id uuid,
  p_recommendation_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  result jsonb;
  audit_row public.audit_logs%rowtype;
  target public.purchase_decision_events%rowtype;
begin
  result := private.undo_purchase_recommendation_action_mise_003c_base(
    p_restaurant_id, p_recommendation_id
  );
  if result->>'outcome' = 'applied' then
    select event.* into target from public.purchase_decision_events event
    where event.restaurant_id = p_restaurant_id
      and event.purchase_recommendation_id = p_recommendation_id
      and (
        (result->>'previous_status' = 'approved'
          and event.decision_type in ('approve', 'approve_with_override'))
        or (result->>'previous_status' = 'dismissed' and event.decision_type = 'dismiss')
      )
      and not exists (
        select 1 from public.purchase_decision_events compensation
        where compensation.restaurant_id = event.restaurant_id
          and compensation.target_event_id = event.id
          and compensation.decision_type = 'undo'
      )
    order by event.sequence desc limit 1;
    if target.id is not null then
      select * into audit_row from public.audit_logs audit
      where audit.restaurant_id = p_restaurant_id
        and audit.entity_id = p_recommendation_id
        and audit.action = 'recommendation_undo'
        and audit.actor_user_id = auth.uid()
      order by audit.created_at desc, audit.id desc limit 1;
      perform private.record_purchase_decision_compensation(
        target, 'undo', audit_row.id, 'audit_log:' || audit_row.id::text,
        audit_row.created_at
      );
    end if;
  end if;
  return result;
end;
$$;

