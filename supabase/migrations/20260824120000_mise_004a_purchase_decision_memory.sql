-- MISE-004A: append-only purchase decision evidence and deterministic patterns.
-- This is bounded decision memory, not recommendation authority. Patterns are
-- computed on read and are not consumed by the recommendation engine.

create table public.purchase_decision_events (
  id uuid primary key default gen_random_uuid(),
  sequence bigint generated by default as identity unique,
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_role text not null check (actor_role in ('owner', 'admin', 'manager')),
  decision_type text not null check (
    decision_type in (
      'approve', 'approve_with_override', 'dismiss', 'undo',
      'exclude_from_learning'
    )
  ),
  purchase_recommendation_id uuid not null,
  inventory_item_id uuid not null,
  supplier_id uuid not null,
  recommendation_source text not null check (
    recommendation_source in ('mise_rules', 'legacy_client')
  ),
  recommendation_unit text not null check (
    length(trim(recommendation_unit)) between 1 and 80
    and recommendation_unit !~ '[[:cntrl:]]'
  ),
  recommended_quantity numeric not null check (
    recommended_quantity > 0 and recommended_quantity <= 1000000000
  ),
  chosen_quantity numeric check (
    chosen_quantity is null or (chosen_quantity > 0 and chosen_quantity <= 1000000000)
  ),
  canonical_unit text not null check (canonical_unit in ('g', 'ml', 'each')),
  canonical_quantity_per_unit numeric not null check (
    canonical_quantity_per_unit > 0 and canonical_quantity_per_unit <= 1000000000
  ),
  recommended_canonical_quantity numeric not null check (
    recommended_canonical_quantity > 0
    and recommended_canonical_quantity <= 1000000000000000000
  ),
  chosen_canonical_quantity numeric check (
    chosen_canonical_quantity is null
    or (
      chosen_canonical_quantity > 0
      and chosen_canonical_quantity <= 1000000000000000000
    )
  ),
  quantity_delta numeric,
  canonical_quantity_delta numeric generated always as (
    chosen_canonical_quantity - recommended_canonical_quantity
  ) stored,
  quantity_ratio numeric check (
    quantity_ratio is null or (quantity_ratio > 0 and quantity_ratio <= 1000000000)
  ),
  planning_revision bigint check (planning_revision is null or planning_revision >= 0),
  context_evidence jsonb not null default '{}'::jsonb check (
    jsonb_typeof(context_evidence) = 'object'
    and pg_column_size(context_evidence) <= 8192
  ),
  target_event_id uuid,
  source_audit_log_id uuid,
  source_event_key text not null check (length(source_event_key) between 8 and 200),
  evidence_version text not null default 'mise.purchase_decision.v1'
    check (evidence_version = 'mise.purchase_decision.v1'),
  occurred_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint purchase_decision_events_restaurant_id_id_key unique (restaurant_id, id),
  constraint purchase_decision_events_source_key unique (restaurant_id, source_event_key),
  constraint purchase_decision_events_target_fk foreign key (restaurant_id, target_event_id)
    references public.purchase_decision_events(restaurant_id, id),
  constraint purchase_decision_events_shape_check check (
    (
      decision_type = 'approve'
      and target_event_id is null
      and chosen_quantity = recommended_quantity
      and chosen_canonical_quantity = recommended_canonical_quantity
      and quantity_delta = 0
      and canonical_quantity_delta = 0
      and quantity_ratio = 1
    )
    or (
      decision_type = 'approve_with_override'
      and target_event_id is null
      and chosen_quantity is not null
      and chosen_quantity <> recommended_quantity
      and chosen_canonical_quantity is not null
      and quantity_delta = chosen_quantity - recommended_quantity
      and canonical_quantity_delta = chosen_canonical_quantity - recommended_canonical_quantity
      and quantity_ratio = chosen_quantity / recommended_quantity
    )
    or (
      decision_type = 'dismiss'
      and target_event_id is null
      and chosen_quantity is null
      and chosen_canonical_quantity is null
      and quantity_delta is null
      and canonical_quantity_delta is null
      and quantity_ratio is null
    )
    or (
      decision_type in ('undo', 'exclude_from_learning')
      and target_event_id is not null
    )
  )
);

create index purchase_decision_events_pattern_idx
on public.purchase_decision_events (
  restaurant_id, inventory_item_id, supplier_id, canonical_unit,
  recommendation_source, occurred_at desc
);
create index purchase_decision_events_recommendation_idx
on public.purchase_decision_events (
  restaurant_id, purchase_recommendation_id, sequence desc
);
create index purchase_decision_events_target_idx
on public.purchase_decision_events (restaurant_id, target_event_id)
where target_event_id is not null;
create unique index purchase_decision_events_one_undo_idx
on public.purchase_decision_events (restaurant_id, target_event_id)
where decision_type = 'undo';
create unique index purchase_decision_events_one_exclusion_idx
on public.purchase_decision_events (restaurant_id, target_event_id)
where decision_type = 'exclude_from_learning';

